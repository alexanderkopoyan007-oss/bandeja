// Ball test lab report: node tools/ball-lab.ts [tag]
// Fires every lab shot (src/sim/lab/ballLab.ts) and writes docs/lab/ball-lab-<tag>.md and .json (tag default
// "now"), so tuning can be compared before and after.
import { writeFileSync, mkdirSync } from 'node:fs';
import { runLab, type ShotSummary } from '../src/sim/lab/ballLab.ts';
import { HIT_FLOOR } from '../src/sim/ball/ball.ts';

const tag = process.argv[2] ?? 'now';
const res = runLab();
const f = (v: number, d = 2): string => (Number.isFinite(v) ? v.toFixed(d) : '-');
const surf = ['open', 'glass', 'mesh', 'floor', 'net'];
const lines: string[] = [];
lines.push(`# Ball lab: ${tag}`, '', 'Generated by `node tools/ball-lab.ts`. Contacts are measured 1/1200 s either side.', '');
let group = '';
for (const s of res) {
  if (s.shot.group !== group) {
    group = s.shot.group;
    lines.push(`## ${group[0]!.toUpperCase()}${group.slice(1)}`, '');
    lines.push('| Shot | Contacts (surface: speed in → out m/s, e_n, tangential kept, angle in → out °, e_x, roll rpm in → out) | Result |', '|---|---|---|');
  }
  const cs = s.run.contacts.map((c) => `${c.kind === HIT_FLOOR ? 'floor' : surf[c.surface]} @(${f(c.x, 1)},${f(c.y, 2)},${f(c.z, 1)}): ${f(c.speedIn, 1)}→${f(c.speedOut, 1)}, e_n ${f(c.en)}, t ${f(c.tKept)}, ${f(c.angIn, 0)}→${f(c.angOut, 0)}°, e_x ${f(c.ex)}, ${f(c.rollIn, 0)}→${f(c.rollOut, 0)}`).join('<br>');
  const extra: string[] = [];
  if (s.shot.id.startsWith('drop')) {
    const apex = s.run.apexAfter - 0.0328;
    extra.push(`rebound ${f(apex * 100, 1)} cm (FIP 135-145)`);
  }
  if (s.glass) {
    const g = s.glass;
    extra.push(`glass at ${f(g.heightAtGlass)} m, ${f(g.speedIntoGlass, 1)}→${f(g.speedOff, 1)} m/s, e_n ${f(g.enGlass)}, apex after ${f(g.apexAfterGlass)} m, comes back ${f(g.comesBack, 1)} m, height 1 m out ${f(g.heightAt1m)} m`);
  }
  if (s.itf) extra.push(`court pace: mu ${f(s.itf.mu)}, e ${f(s.itf.e)}, CPR ${f(s.itf.cpr, 1)}, SPR ${f(s.itf.spr, 1)}`);
  if (s.stats) {
    const st = s.stats;
    extra.push(`${st.n} runs: e_n ${f(st.en[0])} ± ${f(st.en[1])}, tangential kept ${f(st.tKept[0])} ± ${f(st.tKept[1])}, deflection ${f(st.deflect[0], 1)} ± ${f(st.deflect[1], 1)}°`);
  }
  extra.push(`(${s.run.end}; apex after first contact ${f(s.run.apexAfter)} m)`);
  lines.push(`| **${s.shot.id}**: ${s.shot.label} | ${cs || '(none)'} | ${extra.join('<br>')} |`);
}
mkdirSync('docs/lab', { recursive: true });
writeFileSync(`docs/lab/ball-lab-${tag}.md`, lines.join('\n') + '\n');
const json = res.map((s: ShotSummary) => ({ id: s.shot.id, contacts: s.run.contacts, apexAfter: s.run.apexAfter, end: s.run.end, stats: s.stats, glass: s.glass, itf: s.itf }));
writeFileSync(`docs/lab/ball-lab-${tag}.json`, JSON.stringify(json, null, 1));
console.log(lines.join('\n'));
