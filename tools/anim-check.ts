// Animation QA report (Phase 3): plays AI matches with the animated bodies (no browser) and writes what looks wrong
// in motion to docs/lab/anim-check-<tag>.md and .json. See src/render/avatar/animQa.ts for what each number is.
// node tools/anim-check.ts [tag] [seconds] [seeds]
import { readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { parsePlayerAsset } from '../src/render/avatar/asset.ts';
import { runAnimQa, bodyModel, type QaReport } from '../src/render/avatar/animQa.ts';
import { Avatar } from '../src/render/avatar/avatar.ts';
if (process.env.INERT_MASK) Avatar.inertMask = Number(process.env.INERT_MASK);

const tag = process.argv[2] ?? 'now';
const seconds = Number(process.argv[3] ?? 120);
const seeds = Number(process.argv[4] ?? 3);
const inertial = process.env.INERTIAL !== '0';
const gz = readFileSync(new URL('../public/assets/player.bnz', import.meta.url));
const raw = gunzipSync(gz);
const asset = parsePlayerAsset(raw.buffer.slice(raw.byteOffset, raw.byteOffset + raw.byteLength));

const runs: Array<{ seed: number; lefty: boolean; r: QaReport }> = [];
for (let s = 1; s <= seeds; s++) {
  // Left-handers on seeds 3, 5, 6, ... (seed 5's feet flipped 165° before the step fix; seed 3 never showed it).
  const lefty = s % 3 === 0 || s % 5 === 0;
  const t0 = performance.now();
  const r = runAnimQa(asset, { seed: s, seconds, lefty: lefty ? [false, true, true, false] : [], inertial, repeatEvery: 7 });
  runs.push({ seed: s, lefty, r });
  process.stderr.write(`seed ${s}${lefty ? ' (left-handers 1, 2)' : ''}: ${(performance.now() - t0) / 1000 | 0} s\n`);
}
const f = (x: number, d = 1): string => x.toFixed(d);
const pct = (x: number): string => (100 * x).toFixed(2) + '%';
const L: string[] = [];
L.push(`# Animation QA: ${tag}`, '');
L.push(`Generated by \`node tools/anim-check.ts ${tag} ${seconds} ${seeds}\` (AI doubles, ${seconds} s per seed, every sim tick drawn${inertial ? '' : ', inertialization off'}).`);
L.push('Body capsules fitted to the mesh (median vertex distance, m): ' + bodyModel(asset).capsules.map((c) => `${c.name} ${c.r.toFixed(3)}`).join(', ') + '.', '');
L.push('| Seed | Skate (cm/s) | Planted sole p50 / p90 / p99 (cm/s) | On the ground | Below floor (max cm, share) | Racket to ball p50 / p90 (m) | Contact lag p50 / p90 (ms) | Face vs way out p50 / p90 (°) | Pops per min | Racket in body | Hand in torso | Legs through | Net | Glass | Players overlap | Racket in another | Hips from sim p90 / max (m) | NaN |');
L.push('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|');
for (const { seed, lefty, r } of runs) {
  L.push(`| ${seed}${lefty ? ' L' : ''} | ${f(r.feet.skate, 2)} | ${f(r.feet.planted.p50)} / ${f(r.feet.planted.p90)} / ${f(r.feet.planted.p99)} | ${pct(r.feet.groundShare)} | ${f(r.feet.belowMax)} cm, ${pct(r.feet.belowShare)} | ${f(r.contact.dist.p50, 3)} / ${f(r.contact.dist.p90, 3)} | ${f(r.contact.lag.p50 * 1000)} / ${f(r.contact.lag.p90 * 1000)} | ${f(r.contact.face.p50)} / ${f(r.contact.face.p90)} | ${f(r.pops.perMinute, 2)} | ${pct(r.clip.racketBody)} (max ${f(r.clip.racketBodyMax * 100)} cm) | ${pct(r.clip.handTorso)} (max ${f(r.clip.handTorsoMax * 100)} cm) | ${pct(r.clip.legs)} (max ${f(r.clip.legsMax * 100)} cm) | ${pct(r.clip.net)} | ${pct(r.clip.wall)} | ${pct(r.clip.players)} | ${pct(r.clip.racketOther)} | ${f(r.hipsFromSim.p90, 2)} / ${f(r.hipsFromSim.max, 2)} | ${r.nan} |`);
}
L.push('', '## Joint angular speeds (deg/s): p99 / max against what people reach (frames over 1.25x the limit)', '');
const groups = Object.keys(runs[0]!.r.pops.peaks);
L.push('| Seed | ' + groups.join(' | ') + ' |', '|---|' + groups.map(() => '---').join('|') + '|');
for (const { seed, r } of runs) L.push(`| ${seed} | ` + groups.map((g) => { const p = r.pops.peaks[g]!; return `${p.p99 | 0} / ${p.max | 0} (lim ${p.limit}, ${p.over})`; }).join(' | ') + ' |');
L.push('', '## Pops by joint, and the worst moments', '');
for (const { seed, r } of runs) {
  L.push(`- Seed ${seed}: ${r.pops.count} pops ${JSON.stringify(r.pops.byJoint)}; worst: ` + r.pops.worst.slice(0, 6).map((e) => `${e.what} p${e.player} t=${f(e.t, 2)} ${f(e.value)}°`).join(', '));
  L.push(`  fastest one-frame turns: ` + r.pops.turnWorst.slice(0, 4).map((e) => `${e.what} p${e.player} t=${f(e.t, 2)} ${f(e.value)}°`).join(', ') + `; the same moment drawn twice (${r.repeat.frames} frames): ${f(r.repeat.maxDeg, 3)}° at most`);
  L.push(`  clipping worst: ` + r.clip.worst.slice(0, 8).map((e) => `${e.what} p${e.player} t=${f(e.t, 2)}${e.value ? ' ' + f(e.value * 100) + ' cm' : ''}`).join(', '));
  L.push(`  serve (${(r.serve.frames / 120).toFixed(0)} s of serving): racket in body ${pct(r.serve.racketBody)}, hand in torso ${pct(r.serve.handTorso)}, legs through ${pct(r.serve.legs)}, pops ${f(r.serve.popsPerMinute, 1)} per minute`);
  L.push(`  contact by shot: ` + Object.entries(r.contact.byShot).map(([k, v]) => `${k} ${v.n} (p50 ${f(v.p50, 3)}, p90 ${f(v.p90, 3)})`).join(', '));
}
writeFileSync(new URL(`../docs/lab/anim-check-${tag}.md`, import.meta.url), L.join('\n') + '\n');
writeFileSync(new URL(`../docs/lab/anim-check-${tag}.json`, import.meta.url), JSON.stringify(runs, null, 1) + '\n');
console.log(L.join('\n'));
